#!/usr/bin/env python3
"""Generate Markdown and LaTeX tables from MOSS-TTS result JSON files."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def load_json(path: str) -> dict:
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def throughput_markdown(results: list[dict]) -> str:
    lines = [
        "| Model | Mode | Batch size | Throughput audio-s/s | Speedup vs BS=1 |",
        "| --- | --- | ---: | ---: | ---: |",
    ]
    for result in results:
        model = result["model_type"]
        mode = result["mode"]
        for row in result["rows"]:
            lines.append(
                f"| {model} | {mode} | {row['batch_size']} | "
                f"{row['throughput_audio_per_s']:.3f} | {row['speedup_vs_bs1']:.2f}x |"
            )
    return "\n".join(lines) + "\n"


def profile_markdown(results: list[dict]) -> str:
    lines = [
        "| Model | Mode | RTF mean | Total latency mean (s) | FCL mean (s) | Chunks mean |",
        "| --- | --- | ---: | ---: | ---: | ---: |",
    ]
    for result in results:
        model = result["model_type"]
        for mode_result in result["modes"]:
            summary = mode_result["summary"]
            lines.append(
                f"| {model} | {mode_result['mode']} | {summary['rtf_mean']:.3f} | "
                f"{summary['total_latency_s_mean']:.3f} | "
                f"{summary['first_chunk_latency_s_mean']:.3f} | "
                f"{summary['num_chunks_mean']:.2f} |"
            )
    return "\n".join(lines) + "\n"


def throughput_latex(results: list[dict]) -> str:
    lines = [
        "% Throughput table body generated by scripts/summarize_moss_tts_results.py",
        "% Model & Mode & BS & Throughput & Speedup \\\\",
    ]
    for result in results:
        for row in result["rows"]:
            lines.append(
                f"{result['model_type']} & {result['mode']} & {row['batch_size']} & "
                f"{row['throughput_audio_per_s']:.3f} & {row['speedup_vs_bs1']:.2f}$\\times$ \\\\"
            )
    return "\n".join(lines) + "\n"


def profile_latex(results: list[dict]) -> str:
    lines = [
        "% Profile table body generated by scripts/summarize_moss_tts_results.py",
        "% Model & Mode & RTF & Total latency & FCL & Chunks \\\\",
    ]
    for result in results:
        for mode_result in result["modes"]:
            summary = mode_result["summary"]
            lines.append(
                f"{result['model_type']} & {mode_result['mode']} & "
                f"{summary['rtf_mean']:.3f} & {summary['total_latency_s_mean']:.3f} & "
                f"{summary['first_chunk_latency_s_mean']:.3f} & {summary['num_chunks_mean']:.2f} \\\\"
            )
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--throughput-json", action="append", default=[])
    parser.add_argument("--profile-json", action="append", default=[])
    parser.add_argument("--out-dir", required=True)
    args = parser.parse_args()

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    throughput_results = [load_json(path) for path in args.throughput_json]
    profile_results = [load_json(path) for path in args.profile_json]

    if throughput_results:
        (out_dir / "throughput_table.md").write_text(throughput_markdown(throughput_results), encoding="utf-8")
        (out_dir / "throughput_table.tex").write_text(throughput_latex(throughput_results), encoding="utf-8")
    if profile_results:
        (out_dir / "profile_table.md").write_text(profile_markdown(profile_results), encoding="utf-8")
        (out_dir / "profile_table.tex").write_text(profile_latex(profile_results), encoding="utf-8")


if __name__ == "__main__":
    main()
